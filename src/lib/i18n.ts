export const dictionaries: Record<Locale, Dict> = { fr, en, de, es, ru, ar };

export function translate(locale: Locale, key: string): string {
  return dictionaries[locale][key] ?? dictionaries.fr[key] ?? key;
}

/** Nom d'une categorie dans la langue du visiteur (la base garde le nom francais). */
export function categoryLabel(locale: Locale, category: string): string {
  const cle = "cat." + category;
  const texte = translate(locale, cle);
  return texte === cle ? category : texte;
}
